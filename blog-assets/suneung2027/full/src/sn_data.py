def load_sc(path='/home/claude/sn/listen.txt'):
    t = open(path).read()
    t = re.sub(r'이 문제지에 관한 저작권은 한국교육과정평가원에 있습니다\.', '', t)
    pages = re.split(r'- \d+ -\n', t)[1:]
    SC = {}
    for pg in pages:
        lines = [l.strip() for l in pg.split('\n') if l.strip() and not l.startswith('2027학년도') and l.strip() != '영어 영역 듣기평가 대본']
        if not lines: continue
        if lines[0].startswith('16번부터'): n = 16
        else:
            m = re.match(r'^(\d+)\.', lines[0]); n = int(m.group(1)) if m else None
        if not n or n == 17: continue
        body = []
        for l in lines:
            if re.match(r'^(\d+\.|16번부터|\[16|\[3점\])', l) or (l.endswith('고르시오.') and not re.match(r'^[MW]:', l)): continue
            if re.match(r'^(M|W):', l) or l.startswith('[Cell') or not body: body.append(l)
            else: body[-1] += ' ' + l
        SC[n] = '\n'.join(body)
    return SC

